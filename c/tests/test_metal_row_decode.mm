/* tests/test_metal_row_decode.mm -- standalone Metal GPU probe for the
 * mode-3 / mode-1.5 codec-race follow-up (docs/PERFORMANCE_THEORY.md n1:
 * "n1_codec_race_requirement" / "n1_row_independent_coding_caveat_for_mode3").
 *
 * CONTEXT. the codec-race results measured the CPU
 * scalar-C reference decode of all four row-independent int4 entropy codecs
 * (c/codec_row_huff.h, c/codec_row_rans.h, c/codec_row_fse.h,
 * c/codec_row_bitplane.h) and found all three real compressors 36-50x too
 * slow to fuse into a GEMV dequant loop even at the easier miss-path budget
 * -- winner rANS-4way: 1.46 GB/s @ 18 threads vs the ~51 GB/s raw int4
 * nibble-unpack baseline (bitplane+exception's raw-passthrough fallback
 * number, i.e. today's matmul_i4/qt_addrow dequant speed). That merge's own
 * commit message: "container target reverts to case-D int2-only (+33%)
 * unless a Metal row-decoder probe (preregistered budget) surprises."
 * THIS FILE is that probe.
 *
 * SCOPE. Standalone -- new files only (this file + its Makefile target),
 * does NOT touch backend_metal.mm (owned by other in-flight work this
 * session). Own device/queue/library/pipelines, own synthetic census-shaped
 * test data, generated by SAMPLING a quantized-Gaussian distribution (the
 * same family/bisection-on-sigma approach as
 * c/tools/gen_codec_race_synthetic.py's dist_for_entropy, reimplemented
 * here in C++ since this is a standalone .mm with no Python dependency) and
 * then encoded through the ACTUAL MERGED C ENCODER -- c/codec_row_huff.h's
 * huff_build()/huff_encode_row() and c/codec_row_bitplane.h's
 * bitplane_build()/bitplane_encode_row(), plus c/codec_row.h's RowOffsets --
 * not a reimplementation of the codec. Only the GPU decode kernels below
 * are new logic; the bitstreams they consume come from the same header
 * files codec_race.c and the unit tests already exercise on CPU, so a
 * GPU/CPU decode mismatch below is a Metal-side bug, not a data-generation
 * artifact.
 *
 * PREREGISTERED VERDICT LINES (fixed by the task prompt before any kernel
 * in this file was written or run -- see also
 * the Metal row-decode results, whose header states
 * these same two lines ahead of its measured section):
 *
 *   (A) mode-1.5 REVIVED if sustained (steady-state, 1000-iteration)
 *       canonical-Huffman decode-ONLY throughput >= 10 GB/s (raw bytes/s,
 *       the same 0.5-bytes/symbol convention as the CPU study and
 *       codec_race.c: raw_bytes = total_rows * (I/2)).
 *   (B) mode-3 VIABLE if fused decode+GEMV throughput >= 60% of the plain
 *       int4-unpack+GEMV baseline's throughput, same corpus/shape, same
 *       steady-state convention.
 *   Anything less on a line = that mode is DEAD on this hardware for this
 *   format; less on BOTH = entropy coding is DEAD on this hardware, full
 *   stop, record the numbers.
 *
 * WHAT THIS MEASURES (five Metal compute kernels, one MSL library):
 *  1. huff_decode_rows: canonical-Huffman decode via a wide LUT staged
 *     into threadgroup memory once per row-batch (one threadgroup per
 *     ILI_ROWS_PER_TG-row batch, one thread per row -- decode is an
 *     inherently serial bit-walk per row since codeword length is data-
 *     dependent, so row-level parallelism across thousands of independent
 *     GPU threads is the only parallelism a row-CODED format can offer;
 *     that is exactly what this kernel/benchmark measures). The LUT is
 *     cooperatively copied from device memory into threadgroup memory once
 *     per threadgroup (every thread in the batch then does its OWN row's
 *     lookups against the on-chip copy) -- the whole point of staging it
 *     is to turn "one device-memory load per symbol lookup" into "one
 *     device-memory load per LUT entry per threadgroup, then N_symbols
 *     on-chip lookups."
 *  2. int4_unpack_rows: the plain fixed-stride nibble-unpack baseline --
 *     today's matmul_i4/qt_addrow dequant (see c/codec_row_gemv.h's file
 *     header for the exact call sites), same row-per-thread shape, no
 *     bitstream/no LUT, fixed-stride addressing.
 *  3. huff_decode_gemv_fused / int4_gemv_fused_baseline: the mode-3 shape
 *     itself -- decode (or unpack) a row and immediately dot-product it
 *     against a shared activation vector, one thread per output row,
 *     accumulate-as-you-decode (no separate materialize-then-multiply
 *     pass -- each symbol is consumed by an FMA the instant it is decoded),
 *     exactly the fusion c/codec_row_gemv.h sketches in scalar C for the
 *     CPU side.
 *  4. bitplane_decode_rows (the OPTIONAL second format, branchless/
 *     predicated decode -- no LUT, no data-dependent branch, a fixed-cost
 *     gather+select per symbol): included to show the pipeline shape of
 *     the "GPU-oriented exact" candidate. Run on two corpora: the main
 *     census-shaped one (H~2.9 bits/weight, where the CPU study found the
 *     codebook selector correctly falls back to raw passthrough -- expect
 *     the same here) and a separate, deliberately lower-entropy corpus
 *     (forces a narrow base-plane window so the rank-indexed exception
 *     gather is genuinely exercised, not just the degenerate branch).
 *
 * All decode kernels are checked bit-exact against the matching CPU
 * reference decoder (codec_row_huff.h's huff_decode_row /
 * codec_row_bitplane.h's bitplane_decode_row, called directly, unmodified)
 * before any timing number is trusted; the two fused-GEMV kernels are
 * checked against a CPU double-precision reference dot product. Any
 * mismatch is a hard failure (non-zero exit) -- see run_correctness().
 *
 * Build/run: `make metal-row-decode-test` (from c/). No /path/to/models
 * reads. GPU fixture runs only (synthetic data, single process) -- no
 * engine-idle gating needed.
 */
