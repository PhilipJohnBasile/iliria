static const char *ROW_DECODE_SHADER = R"METAL(
#include <metal_stdlib>
using namespace metal;

struct HuffParams     { uint total_rows; uint I; uint maxlen; uint lut_size; };
struct RowParams       { uint total_rows; uint I; };
struct BitplaneParams { uint total_rows; uint I; uint base_bits; uint bias; };

// -- (1) canonical Huffman decode, wide LUT cooperatively staged into
// threadgroup memory once per row-batch; one thread decodes one row's
// entire bitstream (inherently serial: codeword length is data-dependent).
kernel void huff_decode_rows(
    device const uchar *payload      [[buffer(0)]],
    device const uint  *row_offsets  [[buffer(1)]],
    device const uchar *lut_global   [[buffer(2)]],
    device uchar       *out_symbols  [[buffer(3)]],
    constant HuffParams &p           [[buffer(4)]],
    threadgroup uchar  *lut_tg       [[threadgroup(0)]],
    uint tid     [[thread_position_in_threadgroup]],
    uint tg_size [[threads_per_threadgroup]],
    uint row     [[thread_position_in_grid]])
{
    for (uint idx = tid; idx < p.lut_size; idx += tg_size) lut_tg[idx] = lut_global[idx];
    threadgroup_barrier(mem_flags::mem_threadgroup);
    if (row >= p.total_rows) return;

    uint pos = row_offsets[row];
    uint end = row_offsets[row+1];
    ulong acc = 0; int nbits = 0;
    uint maxlen = p.maxlen;
    device uchar *out_row = out_symbols + (ulong)row * p.I;

    for (uint i = 0; i < p.I; i++) {
        while (nbits < (int)maxlen && pos < end) { acc |= (ulong)payload[pos] << nbits; pos++; nbits += 8; }
        uint window = (uint)(acc & (((ulong)1 << maxlen) - 1));
        uchar entry = lut_tg[window];
        uchar sym = entry & 0xF;
        uchar len = entry >> 4;
        out_row[i] = sym;
        acc >>= len; nbits -= (int)len;
    }
}

// -- (2) plain fixed-stride int4 nibble unpack: the matmul_i4/qt_addrow
// baseline, one thread per row, no bitstream/no LUT.
kernel void int4_unpack_rows(
    device const uchar *flat_packed [[buffer(0)]],
    device uchar       *out_symbols [[buffer(1)]],
    constant RowParams &p           [[buffer(2)]],
    uint row [[thread_position_in_grid]])
{
    if (row >= p.total_rows) return;
    uint row_bytes = p.I >> 1;
    device const uchar *w = flat_packed + (ulong)row * row_bytes;
    device uchar *out_row = out_symbols + (ulong)row * p.I;
    for (uint i = 0; i < p.I; i += 2) {
        uchar b = w[i>>1];
        out_row[i]   = b & 0xF;
        out_row[i+1] = b >> 4;
    }
}

// -- (3a) mode-3 shape: Huffman-decode a row and immediately FMA each
// symbol against the shared activation vector x[I] -- decode and consume
// are the SAME loop, nothing materialized row-wide first.
kernel void huff_decode_gemv_fused(
    device const uchar *payload      [[buffer(0)]],
    device const uint  *row_offsets  [[buffer(1)]],
    device const uchar *lut_global   [[buffer(2)]],
    device const float *x            [[buffer(3)]],
    device const float *scale        [[buffer(4)]],
    device float       *y            [[buffer(5)]],
    constant HuffParams &p           [[buffer(6)]],
    threadgroup uchar  *lut_tg       [[threadgroup(0)]],
    uint tid     [[thread_position_in_threadgroup]],
    uint tg_size [[threads_per_threadgroup]],
    uint row     [[thread_position_in_grid]])
{
    for (uint idx = tid; idx < p.lut_size; idx += tg_size) lut_tg[idx] = lut_global[idx];
    threadgroup_barrier(mem_flags::mem_threadgroup);
    if (row >= p.total_rows) return;

    uint pos = row_offsets[row];
    uint end = row_offsets[row+1];
    ulong acc = 0; int nbits = 0;
    uint maxlen = p.maxlen;
    float a = 0.0f;

    for (uint i = 0; i < p.I; i++) {
        while (nbits < (int)maxlen && pos < end) { acc |= (ulong)payload[pos] << nbits; pos++; nbits += 8; }
        uint window = (uint)(acc & (((ulong)1 << maxlen) - 1));
        uchar entry = lut_tg[window];
        uchar sym = entry & 0xF;
        uchar len = entry >> 4;
        float v = (float)((int)sym - 8);          // same signed dequant as qt_addrow's (b&0xF)-8
        a += v * x[i];
        acc >>= len; nbits -= (int)len;
    }
    y[row] = a * scale[row];
}

// -- (3b) plain-int4-unpack GEMV baseline, same fused shape as (3a) but
// reading directly from the flat fixed-stride packed array.
kernel void int4_gemv_fused_baseline(
    device const uchar *flat_packed [[buffer(0)]],
    device const float *x           [[buffer(1)]],
    device const float *scale       [[buffer(2)]],
    device float       *y           [[buffer(3)]],
    constant RowParams &p           [[buffer(4)]],
    uint row [[thread_position_in_grid]])
{
    if (row >= p.total_rows) return;
    uint row_bytes = p.I >> 1;
    device const uchar *w = flat_packed + (ulong)row * row_bytes;
    float a = 0.0f;
    for (uint i = 0; i < p.I; i += 2) {
        uchar b = w[i>>1];
        int v0 = (int)(b & 0xF) - 8;
        int v1 = (int)(b >> 4) - 8;
        a += (float)v0 * x[i] + (float)v1 * x[i+1];
    }
    y[row] = a * scale[row];
}

// -- (4) branchless bitplane+exception decode: fixed per-position cost
// (k base bits + 1 mask bit + an unconditional rank-indexed exception-area
// gather + a bitmask select, no data-dependent branch), mirroring
// codec_row_bitplane.h's bitplane_decode_row exactly. base_bits==4 is the
// raw-passthrough fallback (native packed nibbles, no header). No LUT/no
// threadgroup memory needed -- one thread per row.
kernel void bitplane_decode_rows(
    device const uchar *payload       [[buffer(0)]],
    device const uint  *row_offsets   [[buffer(1)]],
    device uchar       *out_symbols   [[buffer(2)]],
    constant BitplaneParams &p        [[buffer(3)]],
    uint row [[thread_position_in_grid]])
{
    if (row >= p.total_rows) return;
    uint off = row_offsets[row];
    uint end = row_offsets[row+1];
    device const uchar *rowptr = payload + off;
    uint paylen = end - off;
    device uchar *out_row = out_symbols + (ulong)row * p.I;
    uint n = p.I;

    if (p.base_bits == 4) {
        for (uint i = 0; i < n; i += 2) {
            uchar b = rowptr[i>>1];
            out_row[i]   = b & 0xF;
            out_row[i+1] = b >> 4;
        }
        return;
    }

    uint k = p.base_bits;
    uint base_bytes = (n*k + 7) / 8;
    uint mask_bytes  = (n + 7) / 8;
    uint off_base = 2, off_mask = off_base + base_bytes, off_exc = off_mask + mask_bytes;

    ulong acc_b = 0; int nbits_b = 0; uint pos_b = off_base;
    ulong acc_m = 0; int nbits_m = 0; uint pos_m = off_mask;
    uint exc_len = (paylen > off_exc) ? (paylen - off_exc) : 0;
    uint rank = 0;

    for (uint i = 0; i < n; i++) {
        while (nbits_b < (int)k && pos_b < off_mask) { acc_b |= (ulong)rowptr[pos_b] << nbits_b; pos_b++; nbits_b += 8; }
        uint code = (uint)(acc_b & ((1u<<k)-1u));
        acc_b >>= k; nbits_b -= (int)k;

        while (nbits_m < 1 && pos_m < off_exc) { acc_m |= (ulong)rowptr[pos_m] << nbits_m; pos_m++; nbits_m += 8; }
        uint is_exc = (uint)(acc_m & 1u);
        acc_m >>= 1; nbits_m -= 1;

        uint byte_idx = rank >> 1;
        uchar packed_byte = (byte_idx < exc_len) ? rowptr[off_exc + byte_idx] : 0;
        uchar exc_val = ((rank & 1u) == 0) ? (uchar)(packed_byte & 0xF) : (uchar)(packed_byte >> 4);
        uchar base_val = (uchar)(code + p.bias);
        uchar sel = (uchar)0 - (uchar)is_exc;                 // 0x00 or 0xFF, branchless select
        out_row[i] = (uchar)((exc_val & sel) | (base_val & (uchar)~sel));
        rank += is_exc;
    }
}
)METAL";

